"""
Phase 6: Evaluation harness.

Two independent evaluations, both against real ground truth (never
invented numbers):

  A) RETRIEVAL QUALITY — dense vs hybrid vs hybrid+reranked.
     Ground truth here is generated by the rule engine itself: for a
     sample of job roles, "relevant" = the set of candidates the
     deterministic rule engine says are QUALIFIED for that role
     (computed by a full scan over all 10,000 candidates). This
     mirrors your plan's "build your own ground truth" approach and
     produces the Recall@K / MRR / NDCG comparison table for your
     README.

  B) RULE-ENGINE ROLE-PREDICTION ACCURACY — using the 8 hand-labeled
     resumes in test_resumes.json (each with an `expected_roles`
     list). For each, we parse it with the SAME format-agnostic text
     parser used for arbitrary PDFs, run it against all 324 job roles,
     and check whether the roles we say it's QUALIFIED for match the
     labeled expected_roles (precision/recall/F1).

Usage:
    python run_evaluation.py \
        --chunks out/chunks.jsonl --job-rules out/job_rules.json \
        --test-resumes test_resumes.json \
        --skills-list skills_list.csv --skills-db skills_database.json \
        --num-roles 20 --out out/eval_report.json
"""

import argparse
import json
import random

from rag.embeddings import get_embedder
from rag.vector_store import get_vector_store
from rag.hybrid_retrieval import HybridRetriever
from rag.reranker import get_reranker
from rag.rule_engine import evaluate_candidate
from rag.skills_taxonomy import SkillsTaxonomy
from rag.pdf_ingest import parse_resume_text
from rag.eval_metrics import recall_at_k, precision_at_k, reciprocal_rank, ndcg_at_k, precision_recall_f1


def load_chunks(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f]


def build_candidate_profiles(chunks):
    profiles = {}
    for chunk in chunks:
        meta = chunk["metadata"]
        cid = meta["candidate_id"]
        if cid not in profiles:
            profiles[cid] = {
                "candidate_id": cid,
                "skills": meta.get("skills", []),
                "education": meta.get("education", []),
                "experience_years": meta.get("experience_years"),
            }
    return profiles


def build_index(chunks, embed_backend="local_tfidf", store_backend="local"):
    texts = [c["text"] for c in chunks]
    ids = [c["id"] for c in chunks]
    metadatas = [c["metadata"] for c in chunks]
    embedder = get_embedder(embed_backend)
    if hasattr(embedder, "fit"):
        embedder.fit(texts)
    print(f"Embedding {len(texts)} chunks...")
    vectors = embedder.embed(texts)
    store = get_vector_store(store_backend)
    store.upsert(ids, vectors, metadatas)
    retriever = HybridRetriever(store, embedder)
    retriever.index_bm25(ids, texts)
    text_by_id = dict(zip(ids, texts))
    return retriever, text_by_id


def ranked_candidate_ids(chunk_hits, limit=None):
    seen, out = set(), []
    for h in chunk_hits:
        cid = h["id"].split("__")[0]
        if cid not in seen:
            seen.add(cid)
            out.append(cid)
        if limit and len(out) >= limit:
            break
    return out


# ---------------------------------------------------------------- #
# A) Retrieval quality: dense vs hybrid vs hybrid+reranked
# ---------------------------------------------------------------- #
def evaluate_retrieval(chunks, job_rules, profiles, retriever, text_by_id, num_roles, k, seed=42):
    rng = random.Random(seed)
    candidate_roles = [r for r in job_rules if r["required_skills"]]
    rng.shuffle(candidate_roles)

    reranker = get_reranker("local_lexical")
    per_method_metrics = {m: {"recall": [], "precision": [], "mrr": [], "ndcg": []}
                           for m in ["dense", "hybrid", "hybrid_reranked"]}
    roles_evaluated = 0

    for role in candidate_roles:
        if roles_evaluated >= num_roles:
            break

        relevant = {
            cid for cid, profile in profiles.items()
            if evaluate_candidate(role, profile).status == "QUALIFIED"
        }
        if len(relevant) < 2:
            continue  # need at least a couple relevant candidates for meaningful metrics
        roles_evaluated += 1

        query = ", ".join(role["required_skills"] + role.get("preferred_skills", []))

        dense_hits = retriever.dense_only(query, top_k=100)
        dense_ids = ranked_candidate_ids(dense_hits)

        hybrid_hits = retriever.search(query, top_k=100)
        hybrid_ids = ranked_candidate_ids(hybrid_hits)

        hybrid_candidates = [{"id": cid, "text": text_by_id.get(f"{cid}__skills", text_by_id.get(f"{cid}__summary", ""))}
                              for cid in hybrid_ids]
        reranked = reranker.rerank(query, hybrid_candidates, top_n=k)
        reranked_ids = [c["id"] for c in reranked]

        for method, ranked in [("dense", dense_ids), ("hybrid", hybrid_ids), ("hybrid_reranked", reranked_ids)]:
            per_method_metrics[method]["recall"].append(recall_at_k(ranked, relevant, k))
            per_method_metrics[method]["precision"].append(precision_at_k(ranked, relevant, k))
            per_method_metrics[method]["mrr"].append(reciprocal_rank(ranked, relevant))
            per_method_metrics[method]["ndcg"].append(ndcg_at_k(ranked, relevant, k))

    summary = {}
    for method, metrics in per_method_metrics.items():
        n = len(metrics["recall"]) or 1
        summary[method] = {
            f"recall@{k}": round(sum(metrics["recall"]) / n, 4),
            f"precision@{k}": round(sum(metrics["precision"]) / n, 4),
            "mrr": round(sum(metrics["mrr"]) / n, 4),
            f"ndcg@{k}": round(sum(metrics["ndcg"]) / n, 4),
        }
    return summary, roles_evaluated


# ---------------------------------------------------------------- #
# B) Rule-engine role-prediction accuracy on labeled test resumes
# ---------------------------------------------------------------- #
def evaluate_role_prediction(test_resumes_path, job_rules, taxonomy):
    with open(test_resumes_path, encoding="utf-8") as f:
        test_resumes = json.load(f)

    all_titles = {r["job_title"] for r in job_rules}
    per_resume = []
    for tr in test_resumes:
        record = parse_resume_text(tr["resume_text"], taxonomy, candidate_id=tr["name"])
        candidate = {
            "candidate_id": tr["name"],
            "skills": record.skills,
            "education": record.education,
            "experience_years": record.experience_years,
        }
        predicted = {
            role["job_title"] for role in job_rules
            if evaluate_candidate(role, candidate).status == "QUALIFIED"
        }
        expected = {t for t in tr["expected_roles"] if t in all_titles}
        precision, recall, f1 = precision_recall_f1(predicted, expected)
        per_resume.append({
            "name": tr["name"],
            "extracted_skills": record.skills,
            "extracted_education": record.education,
            "extracted_experience_years": record.experience_years,
            "expected_roles": tr["expected_roles"],
            "predicted_qualified_roles": sorted(predicted),
            "precision": round(precision, 3),
            "recall": round(recall, 3),
            "f1": round(f1, 3),
        })

    n = len(per_resume) or 1
    summary = {
        "avg_precision": round(sum(r["precision"] for r in per_resume) / n, 3),
        "avg_recall": round(sum(r["recall"] for r in per_resume) / n, 3),
        "avg_f1": round(sum(r["f1"] for r in per_resume) / n, 3),
    }
    return per_resume, summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chunks", required=True)
    ap.add_argument("--job-rules", required=True)
    ap.add_argument("--test-resumes", required=True)
    ap.add_argument("--skills-list", required=True)
    ap.add_argument("--skills-db", required=True)
    ap.add_argument("--num-roles", type=int, default=20)
    ap.add_argument("--k", type=int, default=10)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    chunks = load_chunks(args.chunks)
    with open(args.job_rules, encoding="utf-8") as f:
        job_rules = json.load(f)
    profiles = build_candidate_profiles(chunks)
    taxonomy = SkillsTaxonomy(args.skills_list, args.skills_db)

    print("=== A) Retrieval quality: dense vs hybrid vs hybrid+reranked ===")
    retriever, text_by_id = build_index(chunks)
    retrieval_summary, roles_evaluated = evaluate_retrieval(
        chunks, job_rules, profiles, retriever, text_by_id, args.num_roles, args.k
    )
    print(f"(evaluated over {roles_evaluated} job roles, ground truth = rule-engine QUALIFIED set)\n")
    print(f"{'Method':<18}{'Recall@'+str(args.k):<12}{'Precision@'+str(args.k):<15}{'MRR':<10}{'NDCG@'+str(args.k):<10}")
    for method, m in retrieval_summary.items():
        print(f"{method:<18}{m[f'recall@{args.k}']:<12}{m[f'precision@{args.k}']:<15}{m['mrr']:<10}{m[f'ndcg@{args.k}']:<10}")

    print("\n=== B) Rule-engine role-prediction accuracy (test_resumes.json) ===")
    per_resume, role_pred_summary = evaluate_role_prediction(args.test_resumes, job_rules, taxonomy)
    for r in per_resume:
        print(f"\n{r['name']}")
        print(f"  Extracted skills: {', '.join(r['extracted_skills'])}")
        print(f"  Expected roles:  {r['expected_roles']}")
        print(f"  Predicted qualified roles: {r['predicted_qualified_roles']}")
        print(f"  Precision={r['precision']}  Recall={r['recall']}  F1={r['f1']}")
    print(f"\nAverage over {len(per_resume)} labeled resumes: "
          f"Precision={role_pred_summary['avg_precision']}  "
          f"Recall={role_pred_summary['avg_recall']}  F1={role_pred_summary['avg_f1']}")

    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            json.dump({
                "retrieval_quality": {"roles_evaluated": roles_evaluated, "summary": retrieval_summary},
                "role_prediction": {"per_resume": per_resume, "summary": role_pred_summary},
            }, f, indent=2, ensure_ascii=False)
        print(f"\nFull report written to {args.out}")


if __name__ == "__main__":
    main()
